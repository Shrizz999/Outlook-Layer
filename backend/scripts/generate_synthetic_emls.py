for item in EMAILS:
    msg = EmailMessage()
    msg["Message-ID"] = f"<{item['id']}@balbird.synthetic>"
    msg["From"] = item["from"]
    msg["To"] = item["to"]
    msg["Subject"] = item["subject"]
    msg["Date"] = item["date"]
    msg.set_content(item["body"])

    eml_path = EMAIL_DIR / item["file"]
    with open(eml_path, "wb") as f:
        f.write(msg.as_bytes())

# Write CSV expected results
csv_path = RESULTS_DIR / "expected_results.csv"
with open(csv_path, "w", newline="", encoding="utf-8") as f:
    writer = csv.DictWriter(f, fieldnames=["id", "file", "intent", "part", "so_po", "dept", "subject"])
    writer.writeheader()
    for item in EMAILS:
        writer.writerow({
            "id": item["id"],
            "file": item["file"],
            "intent": item["intent"],
            "part": item["part"],
            "so_po": item["so_po"],
            "dept": item["dept"],
            "subject": item["subject"],
        })

